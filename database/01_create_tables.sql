-- NOTICE stores issue metadata only. Paid / Payment Pending / Unpaid are derived
-- from PAYS + PAYMENT.Status (and APPEAL). There is no NOTICE.Status column.
CREATE TABLE NOTICE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Issue_date DATE NOT NULL,
    Due_date DATE NOT NULL,
    Fine_amount NUMBER(10,2) NOT NULL,
    Violation_event_id NUMBER NOT NULL,

    CONSTRAINT PK_NOTICE
        PRIMARY KEY (ID),

    CONSTRAINT FK_NOTICE_VIOLATION
        FOREIGN KEY (Violation_event_id)
        REFERENCES VIOLATION_EVENT(ID),

    CONSTRAINT UK_NOTICE_VIOLATION
        UNIQUE (Violation_event_id),

    CONSTRAINT CK_NOTICE_FINE
        CHECK (Fine_amount > 0),

    CONSTRAINT CK_NOTICE_DATES
        CHECK (Due_date >= Issue_date)
);
CREATE TABLE PAYMENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Payment_date DATE NOT NULL,
    Status VARCHAR2(20) NOT NULL,
    Amount NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_PAYMENT
        PRIMARY KEY (ID),

    CONSTRAINT CK_PAYMENT_STATUS
        CHECK (Status IN ('Pending', 'Successful', 'Failed', 'Refunded')),

    CONSTRAINT CK_PAYMENT_AMOUNT
        CHECK (Amount > 0)
);
