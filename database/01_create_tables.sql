CREATE TABLE VEHICLE_STATUS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Vehicle_id NUMBER NOT NULL,
    Dmp_officer_id NUMBER NOT NULL,
    Status_type VARCHAR2(30) NOT NULL,
    Effective_date DATE NOT NULL,
    Expiry_date DATE,

    CONSTRAINT PK_VEHICLE_STATUS
        PRIMARY KEY (ID),

    CONSTRAINT FK_VSTATUS_VEHICLE
        FOREIGN KEY (Vehicle_id)
        REFERENCES VEHICLE(ID),

    CONSTRAINT FK_VSTATUS_DMP
        FOREIGN KEY (Dmp_officer_id)
        REFERENCES DMP_OFFICER(ID),

    CONSTRAINT CK_VSTATUS_TYPE
        CHECK (Status_type IN (
            'Normal',
            'Wanted',
            'Stolen',
            'Unfit',
            'Blacklisted',
            'Recovered',
            'Cleared'
        )),

    CONSTRAINT CK_VSTATUS_DATES
        CHECK (Expiry_date IS NULL OR Expiry_date >= Effective_date)
);
