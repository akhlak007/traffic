-- Non-destructive Oracle course-object upgrade for SMART_TRAFFIC / FREEPDB1.
-- This script does not drop, truncate, reset, or seed existing tables.
SET SQLBLANKLINES ON

-- Apply the previously approved USER rename in place when upgrading an older schema.
DECLARE
    v_old_table NUMBER;
    v_new_table NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_old_table FROM user_tables WHERE table_name = 'USER_ACCOUNT';
    SELECT COUNT(*) INTO v_new_table FROM user_tables WHERE table_name = 'USER';
    IF v_old_table = 1 AND v_new_table = 0 THEN
        EXECUTE IMMEDIATE 'RENAME USER_ACCOUNT TO "USER"';
    END IF;
END;
/

-- Convert older numeric entity keys to identities without changing existing values.
BEGIN
    FOR key_row IN (
        SELECT 'USER' table_name, 'USER_ID' column_name FROM dual UNION ALL
        SELECT 'ZONE', 'ZONE_ID' FROM dual UNION ALL
        SELECT 'ROAD_SEGMENT', 'ROAD_SEGMENT_ID' FROM dual UNION ALL
        SELECT 'CAMERA', 'CAMERA_ID' FROM dual UNION ALL
        SELECT 'VEHICLE_STATUS', 'STATUS_ID' FROM dual UNION ALL
        SELECT 'CAMERA_EVENT', 'EVENT_ID' FROM dual UNION ALL
        SELECT 'NOTICE', 'NOTICE_ID' FROM dual UNION ALL
        SELECT 'PAYMENT', 'PAYMENT_ID' FROM dual UNION ALL
        SELECT 'APPEAL', 'APPEAL_ID' FROM dual UNION ALL
        SELECT 'RHD', 'RHD_ID' FROM dual UNION ALL
        SELECT 'RISK_ANALYSIS', 'ANALYSIS_ID' FROM dual UNION ALL
        SELECT 'VEHICLE_JOURNEY', 'JOURNEY_ID' FROM dual UNION ALL
        SELECT 'CASE_RECORD', 'CASE_ID' FROM dual
    ) LOOP
        DECLARE
            v_table_exists NUMBER;
            v_is_identity NUMBER;
        BEGIN
            SELECT COUNT(*) INTO v_table_exists
            FROM user_tab_columns
            WHERE table_name = key_row.table_name AND column_name = key_row.column_name;

            SELECT COUNT(*) INTO v_is_identity
            FROM user_tab_identity_cols
            WHERE table_name = key_row.table_name AND column_name = key_row.column_name;

            IF v_table_exists = 1 AND v_is_identity = 0 THEN
                EXECUTE IMMEDIATE 'ALTER TABLE "' || key_row.table_name || '" MODIFY "' ||
                    key_row.column_name || '" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)';
            END IF;
        END;
    END LOOP;
END;
/

