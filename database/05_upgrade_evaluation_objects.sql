CREATE OR REPLACE TYPE VEHICLE_REPORT_TYPE AS OBJECT (
    Licence_plate_no VARCHAR2(30),
    Owner_name       VARCHAR2(61),
    Fitness_status   VARCHAR2(20),
    Legal_status     VARCHAR2(30),
    Violation_count  NUMBER
);
/

CREATE OR REPLACE FUNCTION FN_VIOLATION_COUNT (
    p_licence_plate_no IN VARCHAR2
) RETURN NUMBER
AS
    v_plate           VEHICLE.Licence_plate_no%TYPE;
    v_violation_count NUMBER;
BEGIN
    SELECT Licence_plate_no INTO v_plate
    FROM VEHICLE
    WHERE Licence_plate_no = p_licence_plate_no;

    SELECT COUNT(*) INTO v_violation_count
    FROM INVOLVED_IN ii, VEHICLE v
    WHERE v.ID = ii.Vehicle_id
      AND v.Licence_plate_no = p_licence_plate_no;

    RETURN v_violation_count;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20001, 'Vehicle not found');
END;
/

CREATE OR REPLACE VIEW VEHICLE_VIOLATION_VIEW AS
SELECT
    v.Licence_plate_no,
    v.Vehicle_owner_id,
    u.First_name || ' ' || u.Last_name AS Owner_name,
    ve.ID AS Violation_event_id,
    ve.Type AS Violation_type,
    ce.Event_date,
    n.ID AS Notice_id,
    n.Fine_amount,
    CASE
        WHEN n.ID IS NULL THEN 'not-issued'
        WHEN EXISTS (
            SELECT 1 FROM PAYS py
            JOIN PAYMENT p ON p.ID = py.Payment_id
            WHERE py.Notice_id = n.ID AND p.Status = 'Successful'
        ) THEN 'paid'
        WHEN EXISTS (
            SELECT 1 FROM APPEAL a
            WHERE a.Notice_id = n.ID AND a.Review_status = 'Approved'
        ) THEN 'dismissed'
        WHEN EXISTS (
            SELECT 1 FROM APPEAL a
            WHERE a.Notice_id = n.ID
              AND a.Review_status IN ('Pending', 'Under Review')
        ) THEN 'appealed'
        WHEN EXISTS (
            SELECT 1 FROM PAYS py
            JOIN PAYMENT p ON p.ID = py.Payment_id
            WHERE py.Notice_id = n.ID AND p.Status = 'Pending'
        ) THEN 'payment-pending'
        WHEN n.Due_date < SYSDATE THEN 'overdue'
        ELSE 'pending'
    END AS Notice_status
FROM VEHICLE v
JOIN VEHICLE_OWNER vo ON vo.ID = v.Vehicle_owner_id
JOIN "USER" u ON u.ID = vo.ID
JOIN INVOLVED_IN ii ON ii.Vehicle_id = v.ID
JOIN VIOLATION_EVENT ve ON ve.ID = ii.Violation_event_id
JOIN CAMERA_EVENT ce ON ce.ID = ve.ID
LEFT JOIN NOTICE n ON n.Violation_event_id = ve.ID
/

