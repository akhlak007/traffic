INSERT INTO VEHICLE_REPORT
SELECT
    v.ID,
    VEHICLE_REPORT_TYPE(
        v.Licence_plate_no,
        u.First_name || ' ' || u.Last_name,
        v.Fitness_status,
        NVL((
            SELECT vs.Status_type
            FROM VEHICLE_STATUS vs
            WHERE vs.Vehicle_id = v.ID
              AND ROWNUM = 1
        ), 'Normal'),
        FN_VIOLATION_COUNT(v.Licence_plate_no)
    )
FROM VEHICLE v, "USER" u
WHERE v.Vehicle_owner_id = u.ID;
/

CREATE TABLE PENDING_APPEAL_LIST
(
    ID NUMBER,
    Appeal_date DATE,
    Review_status VARCHAR2(20)
);
/

CREATE OR REPLACE PROCEDURE PR_GET_PENDING_APPEALS (
    p_count OUT NUMBER
)
AS
    CURSOR pending_appeal_cursor IS
        SELECT ID, Appeal_date, Review_status
        FROM APPEAL
        WHERE Review_status IN ('Pending', 'Under Review');

    v_appeal pending_appeal_cursor%ROWTYPE;
BEGIN
    p_count := 0;
    DELETE FROM PENDING_APPEAL_LIST;

    OPEN pending_appeal_cursor;

    LOOP
        FETCH pending_appeal_cursor INTO v_appeal;
        EXIT WHEN pending_appeal_cursor%NOTFOUND;

        INSERT INTO PENDING_APPEAL_LIST (ID, Appeal_date, Review_status)
        VALUES (v_appeal.ID, v_appeal.Appeal_date, v_appeal.Review_status);

        p_count := p_count + 1;
    END LOOP;

    CLOSE pending_appeal_cursor;
END;
/

CREATE OR REPLACE PROCEDURE PR_VERIFY_VIOLATION (
    p_event_id   IN NUMBER,
    p_officer_id IN NUMBER,
    p_decision   IN VARCHAR2,
    p_remarks    IN VARCHAR2
)
IS
    v_exists NUMBER;
BEGIN
    IF p_decision NOT IN ('Confirmed', 'Rejected') THEN
        RAISE_APPLICATION_ERROR(-20013, 'Decision must be Confirmed or Rejected');
    END IF;

    SELECT COUNT(*) INTO v_exists FROM VIOLATION_EVENT WHERE Event_id = p_event_id;
    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Violation event not found');
    END IF;

    SELECT COUNT(*) INTO v_exists FROM TRAFFIC_OFFICER WHERE User_id = p_officer_id;
    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(-20012, 'Traffic officer not found');
    END IF;

    SELECT COUNT(*) INTO v_exists FROM MONITORS_VIOLATION WHERE Violation_event_id = p_event_id;
    IF v_exists > 0 THEN
        RAISE_APPLICATION_ERROR(-20014, 'Violation event has already been verified');
    END IF;

    INSERT INTO MONITORS_VIOLATION (
        Violation_event_id, Traffic_officer_id, Monitor_date, Action_taken, Remarks
    ) VALUES (
        p_event_id, p_officer_id, SYSDATE, p_decision, p_remarks
    );
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20014, 'Violation event has already been verified');
END;
/
